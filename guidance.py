def build_guidance(district: str, lang: str) -> str:
    r = assess_risk(district)
    level, key = r["level"], r["key"]
    fill = {"district": DISTRICTS[key][lang], "peak_date": format_date(r["peak_day"], lang)}
    parts = []
    if r["simulated"]:
        parts.append(f"[{LABELS['simulation'][lang]}]")
    parts.append(f"{LABELS['risk'][lang]}: {LEVEL_NAMES[level][lang]}")
    parts.append(f"{LABELS['household'][lang]}:\n" + HOUSEHOLD[level][lang].format(**fill))
    if level in ANNOUNCEMENT:
        parts.append(f"{LABELS['announcement'][lang]}:\n" + ANNOUNCEMENT[level][lang].format(**fill))
    if key in COASTAL:
        parts.append(COASTAL_NOTE[lang])
    return "\n\n".join(parts)


def build_national_summary(lang: str, results=None) -> str:
    results = results if results is not None else scan_country()
    alerts = [r for r in results if r["level"] in ("WATCH", "WARNING", "DANGER")]
    lines = [LABELS["national"][lang]]
    if any(r.get("simulated") for r in results):
        lines.append(f"[{LABELS['simulation'][lang]}]")
    if not alerts:
        lines.append(LABELS["all_normal"][lang])
    else:
        for r in alerts:
            d = DISTRICTS[r["key"]]
            lines.append(f"- {d[lang]}: {LEVEL_NAMES[r['level']][lang]} "
                         f"({LABELS['peak'][lang]} {format_date(r['peak_day'], lang)})")
        lines.append(LABELS["rest_normal"][lang])
    unknown = [DISTRICTS[r["key"]][lang] for r in results if r["level"] == "UNKNOWN"]
    if unknown:
        lines.append(f"{LEVEL_NAMES['UNKNOWN'][lang]}: {', '.join(unknown)}")
    return "\n".join(lines)


def _unavailable(lang: str) -> str:
    return ("বন্যার পূর্বাভাস এখন পাওয়া যাচ্ছে না। অনুমান করবেন না, স্থানীয় প্রশাসনের ঘোষণা শুনুন।"
            if lang == "bn" else
            "The flood forecast is unavailable right now. Do not guess; follow local authority announcements.")


@tool
def get_flood_guidance(district: str) -> str:
    """Get the current river-flood risk and the verified guidance for one district of
    Bangladesh (all 64 districts are covered). Use this whenever someone asks whether
    a place is at risk or what to do. The text is checked by a native speaker and is
    already in the user's language: show it exactly as returned, without translating,
    shortening or rewording it.

    Args:
        district: District name in English or Bengali, e.g. "Kurigram" or "কুড়িগ্রাম"
    """
    lang = _state["language"]
    try:
        text = build_guidance(district, lang)
    except ValueError:
        return ("জেলাটি চেনা যায়নি। বাংলাদেশের ৬৪ জেলার যেকোনো একটির নাম লিখুন।" if lang == "bn"
                else "District not recognised. Please name one of the 64 districts of Bangladesh.")
    except requests.RequestException:
        return _unavailable(lang)
    _state["last_guidance"] = text
    return text


@tool
def get_national_flood_summary() -> str:
    """Check all 64 districts of Bangladesh at once and list the ones with elevated
    river-flood risk. Use this when someone asks about the whole country, a division,
    or "where is flooding expected". Show the result exactly as returned.
    """
    lang = _state["language"]
    try:
        text = build_national_summary(lang)
    except requests.RequestException:
        return _unavailable(lang)
    _state["last_guidance"] = text
    return text
