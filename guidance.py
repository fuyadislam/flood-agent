def format_date(iso_day, lang):
    if not iso_day:
        return "শিগগিরই" if lang == "bn" else "soon"
    _, month, day = (int(p) for p in iso_day.split("-"))
    if lang == "bn":
        return f"{str(day).translate(BN_DIGITS)} {BN_MONTHS[month - 1]}"
    return f"{day} {EN_MONTHS[month - 1]}"


